import { describe, expect, it } from "vitest";
import { applyBlock, renderBlock, selectRules } from "./export.js";
import type { Rule } from "./rule.js";
import type { RulesFile } from "./rulesfile.js";

const src = (pr: number, reviewer: string) => ({
  prNumber: pr,
  reviewer,
  commentUrl: `https://github.com/o/r/pull/${pr}#discussion_r${pr}0`,
});
const rule = (id: string, description: string, confidence: number, sources: Rule["sources"], scope: string[] = []): Rule => ({
  id,
  description,
  scope,
  confidence,
  sources,
});

const file = (rules: Rule[]): RulesFile => ({ version: 1, repo: "o/r", minedAt: "2026-10-19T20:00:00.000Z", rules });

const gate = rule("a", "Use gate() in tests.", 0.6, [src(1, "anna"), src(2, "bob"), src(3, "cy"), src(4, "dan")], ["packages/**/__tests__/**"]);
const hooks = rule("b", "Name hooks\nwith a use prefix.", 0.4, [src(5, "anna"), src(6, "bob")]);
const solo = rule("c", "Single reviewer taste.", 0.75, [src(7, "anna"), src(8, "anna")]);
const weak = rule("d", "Weak rule.", 0.3, [src(9, "anna"), src(10, "bob")]);

describe("selectRules", () => {
  it("drops low confidence and single-reviewer rules, sorts by confidence, and caps the list", () => {
    const all = { format: "claude" as const, includeEmerging: true };
    expect(selectRules([hooks, solo, weak, gate], all).map((r) => r.id)).toEqual(["a", "b"]);
    expect(selectRules([hooks, solo, gate], { ...all, includeSingleReviewer: true }).map((r) => r.id)).toEqual(["c", "a", "b"]);
    expect(selectRules([hooks, gate], { ...all, maxRules: 1 }).map((r) => r.id)).toEqual(["a"]);
    expect(selectRules([weak], { ...all, minConfidence: 0.3 })).toHaveLength(1);
  });

  it("exports only core rules (3+ comments from 2+ reviewers) unless emerging rules are asked for", () => {
    // gate has 4 comments from 4 reviewers; hooks has only 2 comments
    expect(selectRules([hooks, gate], { format: "claude" }).map((r) => r.id)).toEqual(["a"]);
    expect(selectRules([hooks, gate], { format: "claude", includeEmerging: true }).map((r) => r.id)).toEqual(["a", "b"]);
  });
});

describe("renderBlock", () => {
  it("renders Markdown with scope and one citation per pull request, first three only", () => {
    expect(renderBlock(file([hooks, gate]), { format: "claude", includeEmerging: true })).toBe(
      [
        "<!-- precedent:start (generated by precedent from o/r, mined 2026-10-19; edit .precedent/rules.json and re-run `precedent export`, not this block) -->",
        "## Team review rules",
        "",
        "Conventions this team's reviewers enforce. Each rule links to the review comments behind it.",
        "",
        "- Use gate() in tests. (`packages/**/__tests__/**`)",
        "  Why: reviewers asked for this in [#1](https://github.com/o/r/pull/1#discussion_r10), [#2](https://github.com/o/r/pull/2#discussion_r20), [#3](https://github.com/o/r/pull/3#discussion_r30)",
        "- Name hooks with a use prefix.",
        "  Why: reviewers asked for this in [#5](https://github.com/o/r/pull/5#discussion_r50), [#6](https://github.com/o/r/pull/6#discussion_r60)",
        "<!-- precedent:end -->",
      ].join("\n"),
    );
  });

  it("uses the same Markdown for AGENTS.md and bare urls for .cursorrules", () => {
    expect(renderBlock(file([gate]), { format: "agents" })).toBe(renderBlock(file([gate]), { format: "claude" }));
    const cursor = renderBlock(file([gate]), { format: "cursor" });
    expect(cursor).toContain("- Use gate() in tests. (packages/**/__tests__/**)\n  Source: https://github.com/o/r/pull/1#discussion_r10 https://github.com/o/r/pull/2#discussion_r20");
    expect(cursor.split("\n").slice(1).join("\n")).not.toContain("`");
  });

  it("says so when no rule meets the thresholds", () => {
    expect(renderBlock(file([weak]), { format: "claude" })).toContain("No rule met the export thresholds yet.");
  });

  it("is deterministic for the same input", () => {
    const f = file([hooks, gate]);
    expect(renderBlock(f, { format: "claude" })).toBe(renderBlock(f, { format: "claude" }));
  });
});

describe("applyBlock", () => {
  const block = renderBlock(file([gate]), { format: "claude" });
  const newer = renderBlock(file([hooks]), { format: "claude" });

  it("creates the content for a missing or empty file", () => {
    expect(applyBlock(undefined, block)).toBe(`${block}\n`);
    expect(applyBlock("  \n", block)).toBe(`${block}\n`);
  });

  it("appends to an existing file that has no block, keeping its content", () => {
    const out = applyBlock("# My project\n\nBe nice.\n", block);
    expect(out.startsWith("# My project\n\nBe nice.\n\n<!-- precedent:start")).toBe(true);
    expect(out.endsWith("<!-- precedent:end -->\n")).toBe(true);
  });

  it("replaces only the generated block and is idempotent", () => {
    const original = `# Mine\n\nbefore\n\n${block}\n\nafter\n`;
    const updated = applyBlock(original, newer);
    expect(updated).toBe(`# Mine\n\nbefore\n\n${newer}\n\nafter\n`);
    expect(applyBlock(updated, newer)).toBe(updated);
  });

  it("keeps Windows line endings", () => {
    const out = applyBlock("# Mine\r\n\r\nbefore\r\n", block);
    expect(out).toContain("\r\n<!-- precedent:start");
    expect(out.replace(/\r\n/g, "")).not.toContain("\n");
  });
});
